/**
 * Byte helpers that run unchanged in the browser, Web Workers and Electron.
 * Core code uses these instead of Node's Buffer and node:crypto.
 */

const encoder = new TextEncoder();
// ignoreBOM keeps a leading U+FEFF, as Buffer does; the default decoder would drop it and fail the UTF-8 round trip.
const decoder = new TextDecoder("utf-8", { ignoreBOM: true });

/** UTF-8 encoding. Lone surrogates become U+FFFD, matching Buffer.from(text, "utf8"). */
export const utf8Bytes = (text: string): Uint8Array => encoder.encode(text);

/** UTF-8 decoding. Invalid sequences become U+FFFD, matching buffer.toString("utf8"). */
export const utf8Text = (bytes: Uint8Array): string => decoder.decode(bytes);

/** Encoded UTF-8 length without allocating; equals Buffer.byteLength(text, "utf8"). */
export function utf8ByteLength(text: string): number {
  let length = 0;
  for (let index = 0; index < text.length; index++) {
    const unit = text.charCodeAt(index);
    if (unit < 0x80) length += 1;
    else if (unit < 0x800) length += 2;
    else if (unit >= 0xd800 && unit <= 0xdbff && index + 1 < text.length) {
      const next = text.charCodeAt(index + 1);
      if (next >= 0xdc00 && next <= 0xdfff) { length += 4; index++; } else length += 3;
    } else length += 3;
  }
  return length;
}

const HEX = Array.from({ length: 256 }, (_, byte) => byte.toString(16).padStart(2, "0"));

/** Lowercase hex, as buffer.toString("hex") prints it. */
export function hex(bytes: Uint8Array): string {
  let out = "";
  for (const byte of bytes) out += HEX[byte];
  return out;
}

