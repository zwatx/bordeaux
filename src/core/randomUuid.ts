/**
 * A random version 4 UUID in every context. crypto.randomUUID is limited to secure contexts (HTTPS or localhost), and
 * the SystemCore serves this app over plain http, so it falls back to getRandomValues, which every context provides.
 * Kept free of imports: planning workers load it through project ids.
 */
export function randomUuid(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const h = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
